def _paeth(a, b, c):
    p = a + b - c
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    if pb <= pc:
        return b
    return c


def png_encode_rows(rows, bpp, row_filters):
    """Apply PNG filters (PNG spec section 9) to raw 8-bit rows.

    Written from the spec independently of pdfrw's decoder, so a round
    trip through both checks the decoder.  Returns the filtered bytes,
    each row led by its filter-type byte.
    """
    out = bytearray()
    prior = bytes(len(rows[0]))
    for row, ftype in zip(rows, row_filters):
        out.append(ftype)
        for i, x in enumerate(row):
            a = row[i - bpp] if i >= bpp else 0
            b = prior[i]
            c = prior[i - bpp] if i >= bpp else 0
            predictor = (0, a, b, (a + b) // 2, _paeth(a, b, c))[ftype]
            out.append((x - predictor) % 256)
        prior = row
    return bytes(out)

def create_data(nc=1, nr=1, bpc=8, ncolors=1, filter_type=0):
    pixel_size = (bpc * ncolors + 7) // 8
    data = []
    for r in xrange(nr):
        data.append(filter_type if r > 0 else 0) # filter byte
        for c in xrange(nc * pixel_size):
            data.append(r * nc * pixel_size + c * pixel_size)
    data = array.array('B', data)
    logging.debug("Data: %r" % (data))
    return data, nc, nr, bpc, ncolors

def prepend_data_with_filter(data, filter):
    a = array.array('B', data)
    a.insert(0, filter)
    return a

def print_data(data1, data2):
    if data1 is None:
        return
    for b1, b2 in zip(data1, data2):
        b1 = b1 if type(b1) != str else ord(b1)
        b2 = b2 if type(b2) != str else ord(b2)
        logging.error("%4d %4d" % (b1, b2))
    if len(data1) != len(data2):
        logging.error("Mismatched lengths: %d %d" % (len(data1), len(data2)))
    return None

